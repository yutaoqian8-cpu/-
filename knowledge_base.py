def find_role_playbook(text: str) -> dict[str, Any] | None:
    """根据文本（目标岗位/JD/简历）匹配最相关的岗位画像。"""
    value = (text or "").lower()
    best: dict[str, Any] | None = None
    best_hits = 0
    for playbook in ROLE_PLAYBOOK.values():
        hits = sum(1 for alias in playbook["aliases"] if alias.lower() in value)
        if hits > best_hits:
            best = playbook
            best_hits = hits
    return best


def salary_for_role(role_text: str) -> list[dict[str, str]] | None:
    """根据角色文本返回薪资参考区间。"""
    playbook = find_role_playbook(role_text)
    if not playbook:
        return None
    for key, bands in SALARY_REFERENCE.items():
        if playbook is ROLE_PLAYBOOK.get(key):
            return bands
    return None


def salary_for_key(key: str) -> list[dict[str, str]] | None:
    return SALARY_REFERENCE.get(key)


def skill_effort(skill: str) -> str:
    return SKILL_EFFORT.get(skill, "中等")


def learning_path_for(skill: str) -> list[str]:
    return LEARNING_PATHS.get(skill, DEFAULT_LEARNING_PATH)
